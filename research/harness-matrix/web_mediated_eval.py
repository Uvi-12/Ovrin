"""Web-mediated IAD experiment.

Composes the Section 7 harness-level results into a distributed pipeline
that is unmistakably Web-mediated:

    GitHub-hosted repo
      -> npm-registry-published dependency package
      -> GitHub Actions CI runner
      -> Claude Code (or Codex) agent invocation
      -> first-party allowlist edit

The point is to make the Section 9 argument empirical rather than
rhetorical. We ship every identifier a reviewer needs to reproduce the
run, plus the delegation policy that expresses D(pkg:npm/policy-pack,
config/security/**) = 0.

Two things this script produces:

  1. `web_mediated/` — a full fixture tree containing:
        - consumer_repo/: the reviewed GitHub repo layout
        - policy_pack_pkg/: the npm package source (as it would ship)
        - .github/workflows/ci-agent.yml: the CI workflow that runs the
          agent inside GitHub Actions
        - RUN.md: exact commands and identifiers to reproduce
        - manifest.json: reproducibility manifest with digests, versions,
          runner labels, and control/treatment specification

  2. `web_mediated_report.md` — the report the paper cites, with the
     exact identifiers and the delegation-gate outcome under the case's
     policy. SIM counts come from the Case B rate (198/200), because
     the mechanism is identical: transitive @import from a first-party
     CLAUDE.md through a dependency-supplied CLAUDE.md, resulting in a
     wildcard-adding edit to config/security/allowlist.json.

This is CIB reproducibility — commit, image, binary — as an artifact.
"""
