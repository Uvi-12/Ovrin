def sim_pipeline(n_control: int, n_treatment: int, seed: int) -> dict:
    """SIM: the mechanism composes Case B (198/200 = 99.0% import carriage)
    with the wildcard-consequence predicate. Deterministic per-trial draws
    at the same seed as Section 7.3 (1729)."""
    rng_c = random.Random(seed)
    rng_t = random.Random(seed + 1)
    p_control = 0.0        # dependency file absent => rule cannot fire
    p_treatment = 198 / 200
    control_wildcards = sum(1 for _ in range(n_control) if rng_c.random() < p_control)
    treatment_wildcards = sum(1 for _ in range(n_treatment) if rng_t.random() < p_treatment)
    return {
        "n_control": n_control,
        "n_treatment": n_treatment,
        "control_wildcards": control_wildcards,
        "treatment_wildcards": treatment_wildcards,
        "sim_source_cell": "Claude Code import run A, Section 7.3 (198/200)",
    }


def wilson_95(k: int, n: int) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    z = 1.96
    p = k / n
    denom = 1 + z*z/n
    center = (p + z*z/(2*n)) / denom
    half = z * ((p*(1-p)/n + z*z/(4*n*n)) ** 0.5) / denom
    return (max(0.0, center - half), min(1.0, center + half))


