def digest_tree(tree: dict[str, str]) -> str:
    h = hashlib.sha256()
    for k in sorted(tree):
        h.update(k.encode()); h.update(b"\0")
        h.update(tree[k].encode()); h.update(b"\0")
    return h.hexdigest()[:16]


