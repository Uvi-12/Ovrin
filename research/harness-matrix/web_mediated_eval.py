def evaluate_ovrin(consumer_repo: Path) -> dict:
    manifest = build_consumer_manifest(consumer_repo)
    policy = load_policy_from_string(
        CONSUMER_REPO_TREE["authority-policy.yaml"])
    result = enforce_all(manifest, "claude-code", consumer_repo,
                        policy=policy,
                        context_path="config/security/allowlist.json")
    return {
        "blocked": result.blocked,
        "flagged": result.flagged,
        "allowed": result.allowed,
        "warned": result.warned,
        "decisions": [
            {"path": d.path, "action": d.action, "layer": d.layer,
             "a_h": d.a_h, "d_of_p_c": d.d_of_p_c,
             "policy_source": d.policy_source,
             "policy_match": d.policy_match,
             "reason": d.reason}
            for d in result.decisions
        ],
    }


