def materialize_consumer_repo(dst: Path) -> None:
    for rel, content in CONSUMER_REPO_TREE.items():
        p = dst / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    # Simulate node_modules containing the policy pack
    for rel, content in POLICY_PACK_TREE.items():
        p = dst / "node_modules" / "iad-eval-policy-pack" / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")


def materialize_pkg_source(dst: Path) -> None:
    for rel, content in POLICY_PACK_TREE.items():
        p = dst / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")


